import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { strict as assert } from "node:assert";

const root = resolve(import.meta.dirname, "../tools/email-kit/src");
const source = ["config.js","library.js","rules.js","engine.js","conversation.js"].map(f=>readFileSync(resolve(root,f),"utf8")).join("\n");
const { CONFIG, Rules, Engine, Conversation, applyAgency } = new Function(`${source}\nreturn {CONFIG,Rules,Engine,Conversation,applyAgency};`)();
applyAgency(null);
assert.equal(CONFIG.firm.name,"Job Point Consultancy");
assert.equal(CONFIG.profileVersion,"platform-identity-v1");
const today = "2026-11-03";
const advice = (lastSpeaker,lastDate,rest={}) => Conversation.advise({lastSpeaker,lastDate,scenario:"after-reply",...rest},today);
assert.equal(advice("consultant","2026-11-02").action,"pause");
assert.equal(advice("consultant","2026-10-28",{outstanding:"Client decision on proposal"}).action,"follow-up");
assert.equal(advice("client","2026-11-02",{outstanding:"Please clarify scope"}).action,"reply");
assert.equal(advice("","2026-10-28").action,"clarify");
assert.equal(advice("consultant","2026-12-01").action,"clarify");
assert.equal(advice("consultant","2026-10-28",{optedOut:true}).action,"pause");
assert.equal(Conversation.review("From: client@example.org\nDate: Oct 29, 2026\nSubject: Proposal\nCould you clarify the fee?",today).questions.length,1);

const state = Engine.emptyState();
const s = {company:"Acme",recipientName:"Riya Rao",recipientContact:"riya@example.org",channel:"email",responsibility:"decision"};
const intake = {history:"From: Riya\nDate: 2026-10-29\nCould you clarify the scope?",objective:"Hiring discussion",subject:"Re: Hiring",lastSpeaker:"client",lastDate:"2026-10-29",lastText:"Could you clarify the scope?",summary:"Discussed permanent hiring scope.",outstanding:"Clarify the scope",next:"Reply with verified scope"};
const ctx = {today,now:today+"T12:00:00.000Z",actor:"Consultant",source:"test"};
const result = Engine.run(state,"importConversation",{s,intake},ctx);
Engine.applyChanges(state,result.changes);
const conv = state.convs[result.result.convId];
assert.equal(conv.status,"responseReceived");
assert.equal(conv.importedContext.lastSpeaker,"client");
assert.equal(Engine.rows(state,"tasks").filter(t=>t.status==="open").length,1);
assert.equal(Engine.rows(state,"sources")[0].body,intake.history);
const importedForm = {...Engine.formFor(state,conv,{senderName:"Asha",senderRole:"Consultant"}),responseText:intake.lastText,responseCategory:"moreInfo",contextAnswer:"The confirmed scope covers permanent roles.",scenario:"reply",agencyVersion:CONFIG.profileVersion};
const importedValidation = Rules.validate(importedForm,today,[],Engine.trackerView(state));
assert.ok(!importedValidation.blockers.some(b=>b.field==="agencyName"));
assert.match(Conversation.draft(conv.importedContext,importedForm).body,/confirmed scope/);
const replyState = {...importedForm,activeRecordId:conv.id,stage:"followup",priorChannel:"email",priorType:"reply",priorSubject:intake.subject,priorDate:intake.lastDate};
const processed = Engine.run(state,"processResponse",{s:replyState,text:intake.lastText,source:"verified import"},ctx);
Engine.applyChanges(state,processed.changes);
assert.equal(Engine.rows(state,"msgs").filter(m=>m.direction==="in").length,1);
assert.throws(()=>Engine.run(state,"importConversation",{s,intake},ctx),/already exists/);
assert.throws(()=>Engine.run(Engine.emptyState(),"importConversation",{s,intake:{...intake,lastSpeaker:""}},ctx),/Confirm who/);
assert.throws(()=>Engine.run(Engine.emptyState(),"importConversation",{s,intake:{...intake,lastText:""}},ctx),/latest client message/);
const outbound = Engine.emptyState();
const sent = Engine.run(outbound,"importConversation",{s,intake:{...intake,lastSpeaker:"consultant",lastText:"Here is the scope."}},ctx);
Engine.applyChanges(outbound,sent.changes);
assert.equal(outbound.convs[sent.result.convId].status,"awaiting");
assert.equal(outbound.convs[sent.result.convId].lastType,"reply");
const validity = Rules.validate({...s,stage:"first",senderName:"A",senderRole:"Consultant",reason:"role",desired:"call",hiringType:"permanent"},today,[],[]);
assert.ok(!validity.blockers.some(b=>b.field==="agencyName"));
const first = {...s,company:"Cedar Foods",recipientName:"Nina Shah",recipientContact:"nina@cedar.example",senderName:"Asha",senderRole:"Consultant",stage:"first",reason:"role",desired:"call",agencyVersion:CONFIG.profileVersion};
const composed = Rules.compose(first,CONFIG.limits);
const fresh = Engine.emptyState();
const saved = Engine.run(fresh,"saveDraft",{s:first,body:composed.candidates[0].body,subject:composed.candidates[0].subject,ready:true},ctx);
Engine.applyChanges(fresh,saved.changes);
const marked = Engine.run(fresh,"markSent",{s:first,convId:saved.result.convId,msgId:saved.result.msgId,channel:"email",body:composed.candidates[0].body,subject:composed.candidates[0].subject},ctx);
assert.equal(marked.result.status,"awaiting");
console.log("Conversation scenarios passed: first contact without Agency, imported reply, latest consultant reply, duplicate, incomplete history, recent pause, overdue follow-up, opt-out, conflicting date.");
